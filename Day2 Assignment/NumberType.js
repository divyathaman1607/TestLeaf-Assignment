/* Number Type*/
let Num
function Numbertype(Num)
{
    if(Num>0)
    {
        console.log("Postive Number")
    }
    else if(Num<0)
    {
        console.log("Negative")
    }
    else
    {
        console.log("Neutral")
    }
}
Numbertype (10)
Numbertype(-10)
Numbertype(0)

/*Output:Postive Number
Negative
Neutral*/